//! Regenerate the compatibility pack from donor and effective imported materials.
//! DONOR_DB OUT STOCK_DB [PATCH ...]; no material/map/position list.
use anyhow::{Context, Result, ensure};
use serde_json::json;
use std::{collections::BTreeMap, fs, path::PathBuf};
use vostok_resource_porter::content_pack::{Operation, PackManifest, TARGET_BUILD};
use vostok_resource_porter::{BinaryConfig, ResourceDb, vertex_blend_021 as blend};

fn main() -> Result<()> {
    let args: Vec<PathBuf> = std::env::args_os().skip(1).map(PathBuf::from).collect();
    ensure!(args.len() >= 3, "DONOR_DB OUT STOCK_DB [PATCH ...]");
    ensure!(!args[1].exists(), "output must be new");
    let mut donor = ResourceDb::open(&args[0])?;
    let mut port = ResourceDb::open_layers(&args[2..])?;
    let paths: Vec<String> = port
        .paths_with_prefix("material_instances/ported/v021d/")
        .filter(|p| p.ends_with(".material"))
        .map(str::to_owned)
        .collect();
    let mut edits = Vec::new();
    let mut skipped = BTreeMap::new();
    for path in paths {
        let original = path.replacen("material_instances/ported/v021d/", "material_instances/", 1);
        if !donor.is_file(&original) {
            continue;
        }
        let d = BinaryConfig::parse(&donor.read(&original)?)?;
        let mut n = BinaryConfig::parse(&port.read(&path)?)?;
        match blend::classify(&d.root, &n.root)? {
            rule @ blend::Compatibility::Linear => {
                rule.apply(&mut n.root)?;
                let values = [blend::STRENGTH, blend::MASK_SLOT]
                    .into_iter()
                    .map(|key| {
                        use vostok_resource_porter::content_pack::value::{from_config, value_at};
                        Ok((
                            key.to_owned(),
                            from_config(value_at(&n.root, key).context("missing adapted leaf")?)?,
                        ))
                    })
                    .collect::<Result<_>>()?;
                edits.push(Operation::ConfigSet { path, values });
            }
            blend::Compatibility::Unchanged => (),
            unsupported => {
                skipped.insert(path, format!("{unsupported:?}"));
            }
        }
    }
    ensure!(!edits.is_empty(), "no supported materials");
    let mut operations = Vec::new();
    for (suffix, bytes) in [
        ("dds", blend::black_mask()),
        ("options", port.read(blend::MASK_OPTIONS)?),
    ] {
        let path = format!("textures/{}.{suffix}", blend::MASK);
        let output = args[1].join("files").join(&path);
        fs::create_dir_all(output.parent().unwrap())?;
        fs::write(output, bytes)?;
        operations.push(Operation::AddFile { path, source: None });
    }
    let count = edits.len();
    operations.extend(edits);
    let pack = PackManifest {
        format_version: 1,
        id: "v021d-linear-vertex-blend".into(),
        version: "1".into(),
        target_build: TARGET_BUILD.into(),
        description: Some("Restore original unmasked linear vertex weighting in imported 0.21 materials using unchanged native shaders".into()),
        requires: vec!["maps-021d-school-fort".into(), "maps-021d-rudnya".into()],
        base_db_sha256: None,
        operations,
        server: None,
        notes: vec![
            "Generated by linear-vertex-021-pack using the converter's vertex_blend_021 rule; no local/map/position selector.".into(),
            "Only new-engine mask and strength change. Donor-authored falloff 1 and all other authored fields remain. Native diffuse/normal base weight becomes vertex colour; specular/roughness and shader permutations remain unchanged.".into(),
            format!("Unsupported candidates unchanged: {}", serde_json::to_string(&skipped)?),
        ],
    };
    fs::write(args[1].join("pack.json"), serde_json::to_vec_pretty(&pack)?)?;
    println!("{}", json!({"materials":count,"skipped":skipped}));
    Ok(())
}
