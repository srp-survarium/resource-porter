#!/usr/bin/env python3
"""Generate Vostok/Mamayev environment edits after restoring donor lights.

Arguments: RESTORE_OUTPUT_DIR OUTPUT_DIR. The first argument is the output of
examples/restore-021-day-lights.rs, built from pinned donor/stock archives and
the ordered composed inputs. Only scalar/vector environment properties become
edits; no geometry or gameplay data from those inputs is copied.
"""
import json
from pathlib import Path
import sys

from three_maps_021_environment import compatibility_values, equal


def main():
    source_dir, output = map(Path, sys.argv[1:])
    root = Path(__file__).resolve().parents[2]
    profiles = json.loads((root / "ports/three-maps-021-lighting.json").read_text())["profiles"]
    markers = {entry["project"].split("/")[1]: entry["marker"] for entry in profiles
               if entry["project"].endswith("/day/client_project")}
    edits = {"_about": "Original Vostok and Mamayev day environment values, shared original-shader selectors and coordinate/default compatibility. Apply after the donor-light restoration. Generated by resource-porter tools/content/two_maps_021_environment.py.", "set_entry": []}
    environments = json.loads((source_dir / "environments.json").read_text())
    assert {(e["level"], e["mode"]) for e in environments} == {
        (level, mode) for level in ("level_03", "level_06") for mode in (2, 4, 8)}
    for entry in environments:
        before, source = entry["before"], entry["source"]
        # Resource paths retain their existing porter bindings. All authored
        # numeric/boolean properties retain their original values.
        values = {key: value for key, value in source.items()
                  if isinstance(value, (int, float, bool, list)) and key in before}
        values.update(compatibility_values(source, markers[entry["level"]]))
        path = f'projects/v021d_{entry["level"]}/day_{entry["mode"]}/client_project'
        env_path = f'client_objects[{entry["index"]}]/properties'
        changed = {key: value for key, value in values.items() if key in before and not equal(before[key], value)}
        numeric = {key: value for key, value in changed.items() if not isinstance(value, bool)}
        if numeric:
            edits["set_entry"].append({"file": path, "list": "client_objects", "where": {"game_object_type": "environment"},
                "from": {"properties/" + key: before[key] for key in numeric},
                "to": {"properties/" + key: value for key, value in numeric.items()}})
        for key, value in changed.items():
            if isinstance(value, bool):
                edits.setdefault("set_bool", []).append({"file": path, "path": env_path + "/" + key, "from": before[key], "to": value})
        for key, value in values.items():
            if key not in before:
                edits.setdefault("add_value", []).append({"files": [path], "table": env_path, "key": key, "value": value})
        print(path, ", ".join(changed))
    output.mkdir(parents=True, exist_ok=True)
    (output / "v021d-two-maps-environment-1.json").write_text(json.dumps(edits, indent=2) + "\n")


if __name__ == "__main__":
    main()
