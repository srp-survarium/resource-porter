#!/usr/bin/env python3
"""Emit source edit lists for original shader bindings/defaults, without tuning.

Arguments: PORTER DONOR_DB SCHOOL_FORT_PACK RUDNYA_PACK OUTPUT_DIR.
The existing packs already preserve authored environment values. Read those
canonical pack files, not a release patch or an earlier calibrated preview.
"""
import json
import math
from pathlib import Path
import subprocess
import sys


def environment(args):
    leaves = {}
    for line in subprocess.check_output(args + ["--leaves"], text=True).splitlines():
        key, value = line.split("\t", 1)
        leaves[key] = json.loads(value.split(":", 1)[1])
    objects = [key.removesuffix(".game_object_type") for key, value in leaves.items()
               if key.endswith(".game_object_type") and value == "environment"]
    if len(objects) != 1:
        raise ValueError("exactly one environment is required")
    prefix = objects[0] + ".properties."
    return objects[0], {key.removeprefix(prefix): value for key, value in leaves.items()
                        if key.startswith(prefix)}


def equal(a, b):
    if isinstance(a, list) and isinstance(b, list):
        return len(a) == len(b) and all(equal(x, y) for x, y in zip(a, b))
    if isinstance(a, (int, float)) and isinstance(b, (int, float)):
        return math.isclose(a, b, rel_tol=1e-5, abs_tol=1e-5)
    return a == b


def main():
    porter, donor, school_fort, rudnya, out = sys.argv[1:]
    root = Path(__file__).resolve().parents[2]
    profiles = json.loads((root / "ports/three-maps-021-lighting.json").read_text())["profiles"]
    lists = {name: {"_about": "Original 0.21 authored colours and intensities, without artistic calibration. Shared shader marker, cloud coordinate/default conversion and original omitted height-ambient defaults only. Generated by resource-porter tools/content/three_maps_021_environment.py; see its shader and constructor evidence.", "set_entry": []}
             for name in ("v021d-rudnya-environment-1.json", "v021d-school-fort-environment-1.json")}
    for profile in profiles:
        level = profile["project"].split("/")[1]
        _, source = environment([porter, "dump-db-config", "--db", donor, "--path", profile["project"]])
        pack, modes, name = (rudnya, (2, 4), "v021d-rudnya-environment-1.json") if level == "level_01" else (school_fort, (2, 4, 8), "v021d-school-fort-environment-1.json")
        path = f"projects/v021d_{level}/day_2/client_project"
        env_path, before = environment([porter, "dump-config", "--file", str(Path(pack) / "files" / path)])
        # Fail if a pack has already calibrated an authored colour/intensity.
        for key, value in source.items():
            if isinstance(value, str):
                continue  # Texture resource paths are namespaced by the porter.
            if any(word in key for word in ("color", "intensity", "multiplier", "blueshift")):
                if not equal(before[key], value):
                    raise ValueError(f"{level}: authored {key} was changed by the map pack")
        converted = {
            "mie_fog_base_height": int(profile["marker"]),
            # Original uploads (cos,sin); native uploads (sin,cos).
            "sky_clouds_rotation": round((90 - source["sky_clouds_rotation"]) % 360, 6),
            "stratosphere_rotation": round((90 - source["stratosphere_rotation"]) % 360, 6),
            # Defaults established by the original draw/loader. The extra
            # native sunlight multiplier must be neutral, not artistically set.
            "sky_clouds_fog_color": source.get("sky_clouds_fog_color", [1, 1, 1, 1]),
            "use_sky_clouds_lighting": source.get("use_sky_clouds_lighting", False),
            "sky_clouds_sunlight": 1,
            # Original ctor 0x215157 initializes +178h to black, +188h to white;
            # loader 0x2157F7 keeps them when these optional keys are absent.
            "height_based_ambient_low_color": source.get("height_based_ambient_low_color", [0, 0, 0, 1]),
            "height_based_ambient_high_color": source.get("height_based_ambient_high_color", [1, 1, 1, 1]),
        }
        changed = {key: value for key, value in converted.items() if key in before and not equal(before[key], value)}
        booleans = {key: value for key, value in changed.items() if isinstance(value, bool)}
        changed = {key: value for key, value in changed.items() if key not in booleans}
        missing = {key: value for key, value in converted.items() if key not in before}
        for key, value in missing.items():
            lists[name].setdefault("add_value", []).append({
                "files": [f"projects/v021d_{level}/day_{mode}/client_project" for mode in modes],
                "table": env_path + "/properties", "key": key, "value": value})
        for mode in modes:
            for key, value in booleans.items():
                lists[name].setdefault("set_bool", []).append({
                    "file": f"projects/v021d_{level}/day_{mode}/client_project",
                    "path": env_path + "/properties/" + key,
                    "from": before[key], "to": value})
            lists[name]["set_entry"].append({"file": f"projects/v021d_{level}/day_{mode}/client_project", "list": "client_objects",
                "where": {"game_object_type": "environment"},
                "from": {"properties/" + k: before[k] for k in changed},
                "to": {"properties/" + k: v for k, v in changed.items()}})
        print(level, "compatibility conversions:", ", ".join(changed | booleans), "added:", ", ".join(missing))
    Path(out).mkdir(parents=True, exist_ok=True)
    for name, data in lists.items():
        (Path(out) / name).write_text(json.dumps(data, indent=2) + "\n")


if __name__ == "__main__":
    main()
