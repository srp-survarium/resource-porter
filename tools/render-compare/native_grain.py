#!/usr/bin/env python3
"""Extract paired native0.26 aberration permutations differing only in grain.

The generated C table pins each bytecode identity; runtime replacement is opt-in
and requires the source post tail to already supply intentional grain.
"""
import argparse
import hashlib
import json
from pathlib import Path
import struct

def chunks(code):
    count=struct.unpack_from('<I',code,28)[0]
    return {code[o:o+4]:code[o+8:o+8+struct.unpack_from('<I',code,o+4)[0]]
            for o in struct.unpack_from('<'+'I'*count,code,32)}


def reflection(code):
    data=chunks(code)[b'RDEF']
    def name(offset):return data[offset:data.index(0,offset)].decode()
    cb_count,cb_offset,resource_count,resource_offset=struct.unpack_from('<4I',data)
    resources={}
    for i in range(resource_count):
        fields=struct.unpack_from('<8I',data,resource_offset+i*32)
        resources[name(fields[0])]=list(fields[1:])
    constants={}
    for i in range(cb_count):
        fields=struct.unpack_from('<6I',data,cb_offset+i*24)
        variables={}
        for j in range(fields[1]):
            variable=struct.unpack_from('<6I',data,fields[2]+j*24)
            variables[name(variable[0])]=list(variable[1:3])
        constants[name(fields[0])]=variables
    return {'resources':resources,'constants':constants}


p=argparse.ArgumentParser(description=__doc__)
p.add_argument('--database',type=Path,required=True)
p.add_argument('--index',type=Path,required=True)
p.add_argument('--output',type=Path,required=True)
p.add_argument('--header',type=Path,required=True)
a=p.parse_args();a.output.mkdir(parents=True,exist_ok=True)
rows=[]
codes=[]
with a.database.open('rb') as db:
    for resource,(offset,length) in sorted(json.loads(a.index.read_text()).items()):
        if not resource.startswith('shaders/sm_4_0/aberration.ps/'):continue
        key=resource.rsplit('/',1)[1]
        assert len(key)==67 and key[40] in '01'
        db.seek(offset);entry=db.read(length);start=entry.index(b'DXBC')
        size=struct.unpack_from('<I',entry,start+24)[0];code=entry[start:start+size]
        assert len(code)==size and (b't_grain_noise' in code)==(key[40]=='1')
        filename='aberration-'+key[5:7]+'-grain'+key[40]+'.dxbc'
        (a.output/filename).write_bytes(code)
        codes.append(code)
        rows.append({'resource':resource,'key':key,'file':filename,'bytes':size,'grain':key[40]=='1','digest':list(code[4:20]),'sha256':hashlib.sha256(code).hexdigest()})
assert len(rows)==8
for row in rows:
    mate=row['key'][:40]+'0'+row['key'][41:]
    row['grainless_index']=next(i for i,r in enumerate(rows) if r['key']==mate)
    paired=rows[row['grainless_index']]
    before=reflection(codes[rows.index(row)]); after=reflection(codes[row['grainless_index']])
    assert chunks(codes[rows.index(row)])[b'ISGN']==chunks(codes[row['grainless_index']])[b'ISGN']
    mapping=[]
    for name,binding in after['resources'].items():
        original=before['resources'][name]
        if binding[0]==3:
            assert binding[:4]+binding[5:]==original[:4]+original[5:]
            mapping.append({'name':name,'from':original[4],'to':binding[4]})
        else:assert binding==original,(row['file'],name,binding,original)
    for cb,variables in after['constants'].items():
        for name,layout in variables.items():assert before['constants'][cb][name]==layout
    row['binding_contract']={'before':before,'after':after,'samplers':mapping,'input_signature_identical':True}
    row['sampler_count']=len(mapping)
    if row['grain']:
        assert sorted((m['from'],m['to']) for m in mapping)==[(j+1,j) for j in range(len(mapping))]
        assert len(mapping) in (1,2)
lines=['// Generated by native_grain.py from the pinned native0.26 archive.',
       'static const struct { unsigned size; unsigned char digest[16]; unsigned grainless; unsigned sampler_count; const char *file; } native_aberration_shaders[] = {']
for r in rows:
    lines.append('    {%d,{%s},%d,%d,"%s"},'%(r['bytes'],','.join('0x%02x'%b for b in r['digest']),r['grainless_index'],r['sampler_count'],r['file']))
lines+=['};','static int native_aberration_index(const void *code,size_t size) {',
        '    for (unsigned i=0;i<sizeof(native_aberration_shaders)/sizeof(native_aberration_shaders[0]);++i)',
        '        if (size==native_aberration_shaders[i].size && !memcmp((const char *)code+4,native_aberration_shaders[i].digest,16)) return (int)i;',
        '    return -1;','}',
        'static int is_native_aberration(const void *code,size_t size) { return native_aberration_index(code,size)>=0; }']
a.header.write_text('\n'.join(lines)+'\n');(a.output/'manifest.json').write_text(json.dumps(rows,indent=2)+'\n')
print('Eight verified permutations; four exact no-grain counterparts')
