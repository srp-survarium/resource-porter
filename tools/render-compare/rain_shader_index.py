#!/usr/bin/env python3
"""Index exact rain PS identities across pinned archives for read-only capture."""
import argparse
import json
import struct
from pathlib import Path

FAMILIES = {'rain.ps': 23, 'rain_sprite_drops.ps': 24, 'rain_resolve.ps': 25}


def generate(archives, output):
    rows = {}
    for database, index in archives:
        with Path(database).open('rb') as stream:
            for name, (offset, length) in json.loads(Path(index).read_text()).items():
                parts = name.split('/')
                if len(parts) != 4 or parts[:2] != ['shaders', 'sm_4_0'] or parts[2] not in FAMILIES:
                    continue
                stream.seek(offset)
                entry = stream.read(length)
                start = entry.index(b'DXBC')
                size = struct.unpack_from('<I', entry, start + 24)[0]
                code = entry[start:start + size]
                if len(code) != size or size < 32:
                    raise ValueError(name)
                key, kind = (size, code[4:20]), FAMILIES[parts[2]]
                if key in rows and rows[key] != kind:
                    raise ValueError('Ambiguous rain shader: ' + name)
                rows[key] = kind
    if not rows:
        raise ValueError('No rain shaders in supplied archives')
    lines = ['// Generated by rain_shader_index.py from pinned archives.',
             'static const struct { unsigned size, kind; unsigned char digest[16]; } rain_shaders[] = {']
    for (size, digest), kind in sorted(rows.items()):
        lines.append('    {%d,%d,{%s}},' % (size, kind, ','.join('0x%02x' % x for x in digest)))
    output.write_text('\n'.join(lines + ['};']) + '\n')
    print(json.dumps({'identities': len(rows), 'families': sorted(set(rows.values()))}))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--archive', nargs=2, action='append', required=True, metavar=('DATABASE', 'INDEX'))
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    generate(args.archive, args.output)
