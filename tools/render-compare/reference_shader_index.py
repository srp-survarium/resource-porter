#!/usr/bin/env python3
"""Generate a bytecode identity table for read-only v0.10b pass capture."""
import argparse
import json
import struct
from pathlib import Path

FAMILIES = {
    'complex_post_process_blend.ps': 0,
    'atmosphere_clouds_modulate.ps': 1,
    'atmospheric_scattering_on_geometry_add.ps': 3,
    'atmosphere.ps': 4,
    'ssao_filter_upsample_temporal.ps': 5,
    'atmospheric_scattering_on_geometry_mul.ps': 6,
    'resolve_lighting.ps': 7,
    'copy_image.ps': 9,
    'ssao_accumulation.ps': 10,
    'ssao_filter_upsample.ps': 11,
}

def generate(database, index, output):
    rows = {}
    with database.open('rb') as stream:
        for name, (offset, length) in sorted(json.loads(index.read_text()).items()):
            parts = name.split('/')
            if len(parts) != 4 or parts[:2] != ['shaders', 'sm_4_0'] or parts[2] not in FAMILIES:
                continue
            stream.seek(offset)
            entry = stream.read(length)
            start = entry.find(b'DXBC')
            if start < 0:
                raise ValueError(name)
            size = struct.unpack_from('<I', entry, start + 24)[0]
            code = entry[start:start + size]
            if len(code) != size:
                raise ValueError(name)
            key = (size, code[4:20])
            kind = FAMILIES[parts[2]]
            if key in rows and rows[key] != kind:
                raise ValueError('ambiguous shader identity: ' + name)
            rows[key] = kind
    lines = ['// Generated by reference_shader_index.py from the pinned original archive.',
             'static const struct { unsigned size, kind; unsigned char digest[16]; } reference_shaders[] = {']
    for (size, digest), kind in sorted(rows.items()):
        lines.append('    {%d,%d,{%s}},' % (size, kind, ','.join('0x%02x' % x for x in digest)))
    lines.append('};')
    output.write_text('\n'.join(lines) + '\n')
    print(json.dumps({'identities': len(rows), 'families': len(FAMILIES)}))

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--database', type=Path, required=True)
    parser.add_argument('--index', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    generate(args.database, args.index, args.output)
