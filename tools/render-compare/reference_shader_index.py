#!/usr/bin/env python3
"""Generate a bytecode identity table for read-only early-client pass capture."""
import argparse
import gzip
import hashlib
import json
import re
import struct
from pathlib import Path

FAMILIES = {
    'complex_post_process_blend.ps': 0,
    'atmosphere_clouds_modulate.ps': 1,
    'atmosphere_clouds_alpha_blend.ps': 1,
    'atmospheric_scattering_on_geometry_add.ps': 3,
    'atmosphere.ps': 4,
    'ssao_filter_upsample_temporal.ps': 5,
    'atmospheric_scattering_on_geometry_mul.ps': 6,
    'resolve_lighting.ps': 7,
    'copy_image.ps': 9,
    'ssao_accumulation.ps': 10,
    'ssao_filter_upsample.ps': 11,
    'forward_volume_cone_base.ps': 12,
    'environment_probe_lighting.ps': 13,
    'sun.ps': 14,
    'translucency.ps': 15,
    'skylight.ps': 16,
    'accum_sun_mask.ps': 17,
    'temporal_mask.ps': 18,
    'environment_probe_index.ps': 19,
    'dumb.ps': 20,
}

def catalog_index(database, catalog):
    """Use the original shader inventory, verifying every selected archive blob."""
    result = {}
    with gzip.open(catalog, 'rt') as source, database.open('rb') as stream:
        for line in source:
            record = json.loads(line)
            if record['name'] not in FAMILIES:
                continue
            stream.seek(record['offset'])
            data = stream.read(record['blob_size'])
            if hashlib.sha256(data).hexdigest() != record['blob_sha256']:
                raise ValueError('shader catalog/archive mismatch: ' + record['name'])
            result['shaders/sm_4_0/' + record['name'] + '/' + record['permutation']] = (
                record['offset'], record['blob_size'])
    if not result:
        raise ValueError('shader catalog has no selected families')
    return result


def generate(database, index, output, additional=(), symbol='reference_shaders'):
    if not re.fullmatch(r'[A-Za-z_][A-Za-z_0-9]*', symbol):
        raise ValueError('invalid C table identifier')
    rows = {}
    for database, index in [(database, index), *additional]:
        with database.open('rb') as stream:
            entries = index if isinstance(index, dict) else json.loads(index.read_text())
            for name, (offset, length) in sorted(entries.items()):
                parts = name.split('/')
                if len(parts) != 4 or parts[:2] != ['shaders', 'sm_4_0'] or parts[2] not in FAMILIES:
                    continue
                stream.seek(offset)
                entry = stream.read(length)
                start = entry.find(b'DXBC')
                if start < 0:
                    raise ValueError(name)
                size = struct.unpack_from('<I', entry, start + 24)[0]
                code = entry[start:start + size]
                if len(code) != size:
                    raise ValueError(name)
                key = (size, code[4:20])
                kind = FAMILIES[parts[2]]
                if key in rows and rows[key] != kind:
                    raise ValueError('ambiguous shader identity: ' + name)
                rows[key] = kind
    lines = ['// Generated by reference_shader_index.py from the pinned original archive.',
             'static const struct { unsigned size, kind; unsigned char digest[16]; } ' + symbol + '[] = {']
    for (size, digest), kind in sorted(rows.items()):
        lines.append('    {%d,%d,{%s}},' % (size, kind, ','.join('0x%02x' % x for x in digest)))
    lines.append('};')
    output.write_text('\n'.join(lines) + '\n')
    print(json.dumps({'identities': len(rows), 'families': len(FAMILIES)}))

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--database', type=Path, required=True)
    source = parser.add_mutually_exclusive_group(required=True)
    source.add_argument('--index', type=Path)
    source.add_argument('--catalog', type=Path, help='original shaders.jsonl.gz inventory')
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--additional-database', type=Path)
    parser.add_argument('--additional-index', type=Path)
    parser.add_argument('--symbol', default='reference_shaders')
    args = parser.parse_args()
    if bool(args.additional_database) != bool(args.additional_index):
        parser.error('additional database and index must be supplied together')
    additional = [(args.additional_database, args.additional_index)] if args.additional_database else []
    index = catalog_index(args.database, args.catalog) if args.catalog else args.index
    generate(args.database, index, args.output, additional, args.symbol)
