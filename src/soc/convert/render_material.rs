//! Classify X-Ray render shaders into v0.100b material families.
//!
//! A compiled level binds render state by *name*: the shader table stores
//! strings such as `def_shaders\def_aref` that select an X-Ray shader script.
//! Those scripts are not shipped in a form the converter can execute, so the
//! port classifies each name into a family and instantiates a reviewed v0.100b
//! template for that family.
//!
//! The classification is deliberately a closed table. An unrecognised shader is
//! a build failure rather than a silent fall back to the opaque template: the
//! STK2 port's most persistent visual defects all came from surfaces quietly
//! inheriting a generic template whose alpha and blending contract did not
//! match the source.

use std::collections::BTreeMap;

use anyhow::{Result, bail};
use serde::{Deserialize, Serialize};

/// The v0.100b material contract a source shader needs.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum RenderFamily {
    /// Fully opaque, lit by the target's own lighting.
    Opaque,
    /// Opaque, but the source shader consumed baked vertex colour. v0.100b
    /// needs a template whose static vertex-colour stage is enabled, otherwise
    /// the converted geometry selects no shader permutation at all.
    VertexLit,
    /// One-bit alpha cutout: fences, grates, ladders.
    AlphaTested,
    /// Sorted alpha blending: glass and dirty windows.
    Translucent,
    /// Two-sided alpha-tested foliage cards.
    Foliage,
    /// Blended decal laid over other geometry.
    Decal,
    /// Self-illuminated or additive.
    Emissive,
    /// Distant impostor billboards generated by `xrLC`.
    LodImpostor,
}

impl RenderFamily {
    pub fn as_str(self) -> &'static str {
        match self {
            Self::Opaque => "opaque",
            Self::VertexLit => "vertex_lit",
            Self::AlphaTested => "alpha_tested",
            Self::Translucent => "translucent",
            Self::Foliage => "foliage",
            Self::Decal => "decal",
            Self::Emissive => "emissive",
            Self::LodImpostor => "lod_impostor",
        }
    }
}

/// The reviewed classification of every shader Shadow of Chernobyl's compiled
/// levels bind.
///
/// Level-specific shaders (`levels\...`) are ground and road variants of the
/// default opaque contract; they differ from `default` only in the detail and
/// blend layers that v0.100b resolves through its own template.
pub fn default_classification() -> BTreeMap<String, RenderFamily> {
    [
        ("default", RenderFamily::Opaque),
        ("def_shaders\\def_vertex", RenderFamily::VertexLit),
        ("def_shaders\\def_objects_lod", RenderFamily::LodImpostor),
        ("def_shaders\\def_aref", RenderFamily::AlphaTested),
        ("def_shaders\\def_aref_v", RenderFamily::AlphaTested),
        ("def_shaders\\def_trans", RenderFamily::Translucent),
        ("def_shaders\\def_trans_v", RenderFamily::Translucent),
        ("flora\\leaf_wave", RenderFamily::Foliage),
        ("flora\\trunk_wave", RenderFamily::Opaque),
        ("effects\\wallmarkblend", RenderFamily::Decal),
        ("effects\\lightplanes", RenderFamily::Emissive),
        ("selflight", RenderFamily::Emissive),
        ("levels\\escape_asfalt", RenderFamily::Opaque),
        ("levels\\escape_asfalt_noblend", RenderFamily::Opaque),
        ("levels\\escape_grass", RenderFamily::Opaque),
        ("levels\\escape_sand", RenderFamily::Opaque),
    ]
    .into_iter()
    .map(|(shader, family)| (shader.to_owned(), family))
    .collect()
}

/// One render material the port will generate.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct MaterialPlan {
    pub shader_id: u16,
    /// The v0.100b resource name, without namespace or extension.
    pub name: String,
    pub source_shader: String,
    pub family: RenderFamily,
    /// The base texture, as named by the source shader table.
    pub source_diffuse: Option<String>,
    /// Lightmaps `xrLC` baked for this surface. v0.100b lights the world at
    /// runtime and has no binding for them, so they are recorded and dropped.
    pub dropped_lightmaps: Vec<String>,
    /// How many merged surfaces use this material.
    pub surface_count: usize,
}

impl MaterialPlan {
    pub fn target_path(&self, namespace: &str) -> String {
        format!("material_instances/{namespace}/{}.material", self.name)
    }

    /// The reference stored in model settings, which carries neither the
    /// `material_instances/` prefix nor the extension.
    pub fn target_reference(&self, namespace: &str) -> String {
        format!("{namespace}/{}", self.name)
    }
}

/// Classify every shader the merged surfaces actually reference.
///
/// `used` maps shader id to how many surfaces use it. Shaders present in the
/// level table but unused by any converted surface are not classified: an
/// unused shader must not be able to fail a build.
pub fn plan_materials(
    used: &BTreeMap<u16, usize>,
    table: &crate::soc::codec::level::ShaderTable,
    classification: &BTreeMap<String, RenderFamily>,
) -> Result<Vec<MaterialPlan>> {
    let mut plans = Vec::with_capacity(used.len());
    let mut unknown = Vec::new();
    for (shader_id, surface_count) in used {
        let entry = table.get(*shader_id)?;
        let Some(family) = classification.get(&entry.shader).copied() else {
            unknown.push(entry.shader.clone());
            continue;
        };
        plans.push(MaterialPlan {
            shader_id: *shader_id,
            name: format!("shader_{shader_id:04}"),
            source_shader: entry.shader.clone(),
            family,
            source_diffuse: entry.base_texture().map(ToOwned::to_owned),
            dropped_lightmaps: entry.lightmaps().to_vec(),
            surface_count: *surface_count,
        });
    }
    if !unknown.is_empty() {
        unknown.sort();
        unknown.dedup();
        bail!(
            "the level binds render shaders with no reviewed v0.100b family: {unknown:?}; \
             add them to render_shader_families"
        );
    }
    Ok(plans)
}

/// Reject a classification override for a shader the level does not bind.
pub fn validate_override_usage(
    overrides: &BTreeMap<String, RenderFamily>,
    used_shaders: &std::collections::BTreeSet<String>,
) -> Result<()> {
    let stale: Vec<&String> = overrides
        .keys()
        .filter(|shader| !used_shaders.contains(*shader))
        .collect();
    if !stale.is_empty() {
        bail!("render shader family overrides no longer apply to any bound shader: {stale:?}");
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::soc::codec::level::parse_shaders;

    fn shader_table(entries: &[&str]) -> crate::soc::codec::level::ShaderTable {
        let mut payload = (entries.len() as u32).to_le_bytes().to_vec();
        for entry in entries {
            payload.extend_from_slice(entry.as_bytes());
            payload.push(0);
        }
        let mut level = 2_u32.to_le_bytes().to_vec();
        level.extend_from_slice(&(payload.len() as u32).to_le_bytes());
        level.extend_from_slice(&payload);
        parse_shaders(&level).unwrap()
    }

    #[test]
    fn covers_every_shader_family_the_cordon_port_recorded() {
        let classification = default_classification();
        for shader in [
            "default",
            "def_shaders\\def_vertex",
            "def_shaders\\def_objects_lod",
            "effects\\wallmarkblend",
            "flora\\leaf_wave",
            "flora\\trunk_wave",
            "def_shaders\\def_trans_v",
            "def_shaders\\def_trans",
            "def_shaders\\def_aref",
            "selflight",
            "def_shaders\\def_aref_v",
            "levels\\escape_sand",
            "levels\\escape_grass",
            "levels\\escape_asfalt_noblend",
            "levels\\escape_asfalt",
            "effects\\lightplanes",
        ] {
            assert!(
                classification.contains_key(shader),
                "{shader} has no reviewed family"
            );
        }
    }

    #[test]
    fn plans_one_material_per_bound_shader() {
        let table = shader_table(&["", "default/prop\\prop_bochka,lm_l01#0", "flora\\leaf_wave/trees\\trees_leaves"]);
        let used = BTreeMap::from([(1_u16, 3_usize), (2, 1)]);
        let plans = plan_materials(&used, &table, &default_classification()).unwrap();
        assert_eq!(plans.len(), 2);
        assert_eq!(plans[0].name, "shader_0001");
        assert_eq!(plans[0].family, RenderFamily::Opaque);
        assert_eq!(plans[0].source_diffuse.as_deref(), Some("prop\\prop_bochka"));
        assert_eq!(plans[0].dropped_lightmaps, ["lm_l01#0"]);
        assert_eq!(plans[1].family, RenderFamily::Foliage);
        assert_eq!(
            plans[0].target_path("ported/soc/cordon"),
            "material_instances/ported/soc/cordon/shader_0001.material"
        );
        assert_eq!(
            plans[0].target_reference("ported/soc/cordon"),
            "ported/soc/cordon/shader_0001"
        );
    }

    #[test]
    fn fails_closed_on_an_unclassified_shader() {
        let table = shader_table(&["", "water\\water_normal/water\\water"]);
        let used = BTreeMap::from([(1_u16, 1_usize)]);
        let error = plan_materials(&used, &table, &default_classification())
            .unwrap_err()
            .to_string();
        assert!(error.contains("no reviewed v0.100b family"), "{error}");
        assert!(error.contains("water\\\\water_normal"), "{error}");
    }

    #[test]
    fn ignores_shaders_no_surface_binds() {
        let table = shader_table(&["", "default/prop\\a", "water\\water_normal/water\\water"]);
        let used = BTreeMap::from([(1_u16, 1_usize)]);
        let plans = plan_materials(&used, &table, &default_classification()).unwrap();
        assert_eq!(plans.len(), 1);
    }

    #[test]
    fn rejects_a_stale_family_override() {
        let overrides = BTreeMap::from([("water\\water".to_owned(), RenderFamily::Translucent)]);
        let used = std::collections::BTreeSet::from(["default".to_owned()]);
        assert!(validate_override_usage(&overrides, &used).is_err());
    }
}
