    #[test]
    fn a_name_override_beats_the_recorded_state() {
        let overrides = default_name_overrides();
        // Shares its state with the water shaders, but is a wallmark.
        let blender = blender_for("S_SET", 2, true, "effects\\wallmarkblend");
        assert_eq!(
            classify("effects\\wallmarkblend", &blender, &overrides),
            Some(RenderFamily::Decal)
        );
        // Water carries the same state as the wallmark and as any other sorted
        // overlay; all three are separated only by name.
        let water = blender_for("S_SET", 2, true, "effects\\water");
        assert_eq!(
            classify("effects\\water", &water, &overrides),
            Some(RenderFamily::Water)
        );
        let overlay = blender_for("S_SET", 2, true, "effects\\some_overlay");
        assert_eq!(
            classify("effects\\some_overlay", &overlay, &overrides),
            Some(RenderFamily::Translucent)
        );
    }

    fn shader_table(entries: &[&str]) -> crate::soc::codec::level::ShaderTable {
        let mut payload = (entries.len() as u32).to_le_bytes().to_vec();
        for entry in entries {
            payload.extend_from_slice(entry.as_bytes());
            payload.push(0);
        }
        let mut level = 2_u32.to_le_bytes().to_vec();
        level.extend_from_slice(&(payload.len() as u32).to_le_bytes());
        level.extend_from_slice(&payload);
        parse_shaders(&level).unwrap()
    }

    fn library(entries: &[(&str, &str, i32, bool)]) -> BTreeMap<String, Blender> {
        entries
            .iter()
            .map(|(name, class, priority, sorting)| {
                ((*name).to_owned(), blender_for(class, *priority, *sorting, name))
            })
            .collect()
    }

    #[test]
    fn plans_one_material_per_bound_shader() {
        let table = shader_table(&[
            "",
            "default/prop\\prop_bochka,lm_l01#0",
            "flora\\leaf_wave/trees\\trees_leaves",
        ]);
        let library = library(&[
            ("default", "LM", 1, false),
            ("flora\\leaf_wave", "D_TREE", 1, false),
        ]);
        let used = BTreeMap::from([(1_u16, 3_usize), (2, 1)]);
        let plans = plan_materials(&used, &table, &library, &default_name_overrides()).unwrap();
        assert_eq!(plans.len(), 2);
        assert_eq!(plans[0].name, "shader_0001");
        assert_eq!(plans[0].family, RenderFamily::Opaque);
        assert_eq!(plans[0].source_diffuse.as_deref(), Some("prop\\prop_bochka"));
        assert_eq!(plans[0].dropped_lightmaps, ["lm_l01#0"]);
        assert_eq!(plans[1].family, RenderFamily::Foliage);
        assert_eq!(
            plans[0].target_path("ported/soc/cordon"),
            "material_instances/ported/soc/cordon/shader_0001.material"
        );
    }

