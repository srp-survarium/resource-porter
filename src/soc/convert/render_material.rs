//! Classify X-Ray render shaders into v0.100b material families.
//!
//! A compiled level binds render state by *name*: the shader table stores
//! strings such as `def_shaders\def_aref` that select an X-Ray shader script.
//! Those scripts are not shipped in a form the converter can execute, so the
//! port classifies each name into a family and instantiates a reviewed v0.100b
//! template for that family.
//!
//! The classification is deliberately a closed table. An unrecognised shader is
//! a build failure rather than a silent fall back to the opaque template: the
//! STK2 port's most persistent visual defects all came from surfaces quietly
//! inheriting a generic template whose alpha and blending contract did not
//! match the source.

use std::collections::BTreeMap;

use anyhow::{Result, bail};

use crate::soc::codec::blender::Blender;
use serde::{Deserialize, Serialize};

/// The v0.100b material contract a source shader needs.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum RenderFamily {
    /// Fully opaque, lit by the target's own lighting.
    Opaque,
    /// Opaque, but the source shader consumed baked vertex colour. v0.100b
    /// needs a template whose static vertex-colour stage is enabled, otherwise
    /// the converted geometry selects no shader permutation at all.
    VertexLit,
    /// One-bit alpha cutout: fences, grates, ladders.
    AlphaTested,
    /// Sorted alpha blending: glass and dirty windows.
    Translucent,
    /// Two-sided alpha-tested foliage cards.
    Foliage,
    /// Blended decal laid over other geometry.
    Decal,
    /// Self-illuminated or additive.
    Emissive,
    /// Vertex-lit *and* alpha-tested. X-Ray states these separately (`V_AREF`),
    /// and collapsing them onto `AlphaTested` drops the static vertex-colour
    /// flag — the exact omission behind the STK2 `shader_source == 0` crash.
    VertexLitAlphaTested,
    /// Distant impostor billboards generated by `xrLC`.
    ///
    /// Currently unreachable, and deliberately kept. `def_shaders\def_objects_lod`
    /// was read as naming these and does not — it names the objects that *have*
    /// impostors. The impostors themselves are `MT_LOD` visuals carrying a
    /// `LODDEF2` chunk of billboard quads, which the converter drops before any
    /// shader is consulted, so no shader reaches this family today. It stays
    /// because porting those visuals is a live option and this is the contract
    /// they would need.
    LodImpostor,
    /// Wind-free flora geometry: tree trunks.
    ///
    /// X-Ray splits its wave shaders by name — `flora\leaf_wave` for canopy and
    /// `flora\trunk_wave` for the trunk beneath it — but both are class
    /// `D_TREE`, so the recorded state cannot separate them. Collapsed onto
    /// [`Self::Foliage`], a trunk inherits the leaf template's
    /// `wind_motion = 2` and the whole tree sways as one, boles included.
    ///
    /// The distinction is a target material setting rather than a family in the
    /// engine's eyes: `flora/poplar_leaves_02` sets `wind_motion = 2`,
    /// `flora/sosna_bark_lod` sets `0`. Splitting the family is how the port
    /// selects between them.
    Bark,
    /// The level's own ground, rendered by the target's terrain shader.
    ///
    /// The two engines build terrain differently. X-Ray stretches a *unique*
    /// colour map across the whole level -- Cordon's is one 2048x2048 image
    /// over 1,445 world units, 0.7m per texel -- and blends a tiled detail
    /// texture over it at close range. v0.100b has no stretched map at all:
    /// `g_stage_terrain` takes four tiled layers and paints them across the
    /// world with a mask, and the large-scale variation *is* the mask.
    ///
    /// So the port uses both. The source colour map becomes layer 0 at tile 1,
    /// which keeps X-Ray's paths and stains, and a tiled layer supplies the
    /// close-range detail the colour map cannot carry. The mask that mixes
    /// them is generated per map rather than inherited, because the shipped
    /// one is level_03's ground painted for level_03's layout.
    ///
    /// Only textures and tile *constants* may differ from the template.
    /// `shaders/masks` lists `CONFIG_NUM_USED_TERRAIN_LAYERS` and
    /// `CONFIG_TDETAIL` among the fourteen macros forming this shader's
    /// permutation, so changing the layer count or enabling the detail slot
    /// asks for a shader that was never compiled.
    ///
    /// **Not currently selected by anything.** Built and run against Cordon,
    /// it rendered the ground pure white. What was learned from that run, for
    /// whoever picks it up:
    ///
    /// * the material is right — it compiles, and every field outside textures
    ///   and tile constants is byte-identical to `terrain/03_base_final`;
    /// * the generated mask reaches the shader — moving one channel from 128 to
    ///   0 visibly changed what the ground rendered;
    /// * the source colour map is intact and correctly bound;
    /// * and yet `texture_diffuse_0` never appears in the result. The next
    ///   thing to test is the *channel order*: writing the weights into blue
    ///   rather than red would say whether build 802's
    ///   `terrain_gbuffer_pass.ps` reads the mask as BGRA, which would mean the
    ///   layers rendered so far were the template's, not this map's.
    ///
    /// That shader is the missing piece. It is a compiled blob in the database
    /// with no source in the reconstruction, and the later-build
    /// `terrain_material_pass.ps` this port's arithmetic was derived from is a
    /// different generation of the same effect.
    ///
    /// Reaching it needs no code: a manifest's `render_shader_families` can map
    /// `levels\escape_grass` and its siblings onto this family per map.
    Terrain,
    /// A water surface, rendered by the target's own water shader.
    ///
    /// X-Ray water carries no usable appearance in its geometry or its texture
    /// alone: `water.vs` displaces the vertices as waves and builds ripples
    /// from two normal maps offset by world position and animated per frame,
    /// so the level authors had no reason to give the plane a sensible tiling.
    /// `mp_pool`'s water spans 42 world units in 3 UV units. Ported as a
    /// translucent surface it reads as a static green pattern, whatever the
    /// tiling — the motion *was* the water.
    ///
    /// v0.100b has its own water shader (`forward_simple_water`, with wave
    /// power, fog colour and local reflections), so the port hands it the plane
    /// and lets the target animate it. Nothing from the source is bound: this
    /// family carries no diffuse.
    ///
    /// Like [`Self::LodImpostor`], no blender state selects this — the water
    /// shaders share `S_SET` priority 2 sorted with every other blended
    /// overlay, so only a declared name override distinguishes them.
    Water,
}

impl RenderFamily {
    /// Every family. A manifest must name a v0.100b template for each, because
    /// the family is chosen from the source and cannot be declined later.
    pub const ALL: &'static [Self] = &[
        Self::Opaque,
        Self::VertexLit,
        Self::AlphaTested,
        Self::Translucent,
        Self::Foliage,
        Self::Decal,
        Self::Emissive,
        Self::VertexLitAlphaTested,
        Self::LodImpostor,
        Self::Bark,
        Self::Terrain,
        Self::Water,
    ];

    pub fn as_str(self) -> &'static str {
        match self {
            Self::Opaque => "opaque",
            Self::VertexLit => "vertex_lit",
            Self::AlphaTested => "alpha_tested",
            Self::Translucent => "translucent",
            Self::Foliage => "foliage",
            Self::Decal => "decal",
            Self::Emissive => "emissive",
            Self::VertexLitAlphaTested => "vertex_lit_alpha_tested",
            Self::LodImpostor => "lod_impostor",
            Self::Bark => "bark",
            Self::Terrain => "terrain",
            Self::Water => "water",
        }
    }
}

/// Classify one shader from the blender state `shaders.xr` records for it.
///
/// Two axes, both read from the file rather than inferred from the name:
///
/// * the **class id** gives lighting and animation — `LM` lightmapped, `V`
///   vertex-lit, `D_TREE` wind-animated, `BmmDold` bump-mapped ground,
///   `S_SET` a screen-space effect blend;
/// * **priority** and **strict sorting** give blend behaviour, in three legible
///   tiers: 1 opaque, 2 sorted blend, 3 additive.
///
/// Neither axis alone is enough. `def_shaders\def_aref` and
/// `def_shaders\def_trans` share class `LM_AREF` and differ only in the second
/// axis; `def_shaders\def_vertex` and `effects\lightplanes` share class `V` and
/// differ only in priority. Classifying on class alone would merge a hard
/// cutout with a blended surface.
pub fn classify_state(class: &str, priority: i32, strict_sorting: bool) -> Option<RenderFamily> {
    // Priority 3 is X-Ray's additive tier, whatever the class carries.
    if priority >= 3 {
        return Some(RenderFamily::Emissive);
    }
    let blended = strict_sorting;
    Some(match (class, blended) {
        // Lightmapped opaque, and the per-level bump-mapped ground variants.
        ("LM", false) | ("BmmDold", false) => RenderFamily::Opaque,
        // Lightmapped cutout, or the same class sorted into a blend.
        ("LM_AREF", false) => RenderFamily::AlphaTested,
        ("LM_AREF", true) => RenderFamily::Translucent,
        // Vertex-lit, with and without a cutout.
        ("V", false) => RenderFamily::VertexLit,
        ("V_AREF", false) => RenderFamily::VertexLitAlphaTested,
        ("V_AREF", true) => RenderFamily::Translucent,
        // Wind-animated foliage: leaves and trunks share this class.
        ("D_TREE", false) => RenderFamily::Foliage,
        // Screen-set effects. Unsorted ones are unlit sprites; sorted ones are
        // blended overlays. The water shaders live here too, and are lifted out
        // by name into `RenderFamily::Water`.
        ("S_SET", false) => RenderFamily::Emissive,
        ("S_SET", true) => RenderFamily::Translucent,
        // Lightmap + emissive bump, unsorted: treated as a cutout.
        ("LmEbB", false) => RenderFamily::AlphaTested,
        _ => return None,
    })
}

/// Name-keyed judgements the recorded state cannot express.
///
/// Kept deliberately tiny. Every entry here is a case where two shaders carry
/// identical blender state but different intent, so the difference is only
/// available from the name — and each one has to earn its place.
pub fn default_name_overrides() -> BTreeMap<String, RenderFamily> {
    [
        // Shares `S_SET` priority 2 / sorted with the water shaders, but it is
        // a wallmark laid over other geometry, not a surface in its own right.
        ("effects\\wallmarkblend", RenderFamily::Decal),
        // The water shaders share that same state, so only the name separates
        // them from any other blended overlay. They go to the target's own
        // water shader rather than to a blended texture; see
        // `RenderFamily::Water`.
        ("effects\\water", RenderFamily::Water),
        ("effects\\waterstuden", RenderFamily::Water),
        ("effects\\waterryaska", RenderFamily::Water),
        // Not an impostor. The name says "objects that have a LOD", and the
        // shader is on the *object*, so that `xrLC` may generate a billboard
        // for it; the billboard itself is an `MT_LOD` visual with a `LODDEF2`
        // chunk, which this port drops before it reaches a material at all.
        //
        // Cordon's 37 surfaces on this shader are its solid props: every
        // vehicle, the barrels and crates, the roadblocks, the rocks, the tree
        // boles, and the Monolith corpses. They are class `D_TREE` only because
        // X-Ray renders them through the tree path, and reading that as foliage
        // sent them to `flora/sosna_bark_lod`, whose contract they do not meet
        // on four separate counts: `use_alpha_test` at 0.5 against a diffuse
        // whose alpha is gloss, `two_sided`, a pine-bark translucency map, and
        // a green `constant_diffuse_attenuation_color`. A truck came out
        // blotched green and tan.
        //
        // Opaque rather than alpha-tested because the alpha would have to mean
        // a cutout for that to be safe, and it does not: 36 of the 37 textures
        // are DXT1 with no alpha channel at all, and the one DXT5 is a UAZ
        // body whose alpha is gloss.
        ("def_shaders\\def_objects_lod", RenderFamily::Opaque),
        // Canopy and trunk share class `D_TREE`; only the name says which is
        // which, and only the canopy should move.
        ("flora\\trunk_wave", RenderFamily::Bark),
    ]
    .into_iter()
    .map(|(shader, family)| (shader.to_owned(), family))
    .collect()
}

